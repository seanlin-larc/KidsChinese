const RANK = new Map();
[...CHARS].forEach((c, i) => { if (!RANK.has(c)) RANK.set(c, i + 1); });

/** Position of a character in CHARS (1 = most frequent), or Infinity when it is not in the list. */
export function charRank(c) {
  return RANK.get(c) ?? Infinity;
}

/** The lowest level that has every character of the word, or null when no level has them all. */
export function levelOfWord(w) {
  const worst = Math.max(...[...w].map(charRank));
  const level = LEVELS.find((l) => worst <= l.size);
  return level ? level.lv : null;
}
